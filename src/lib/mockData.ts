const NEWS_SOURCES = ['DSE Newsroom', 'Financial Express', 'Dhaka Tribune Business', 'BSS Wire', 'The Business Standard'];

function generateNews(ticker: string, name: string, rng: RNG): NewsItem[] {
  const count = rng.int(3, 6);
  const items: NewsItem[] = [];
  const now = new Date();
  for (let i = 0; i < count; i++) {
    const template = rng.pick(NEWS_TEMPLATES);
    const daysAgo = rng.int(1, 30);
    const date = new Date(now);
    date.setDate(date.getDate() - daysAgo);
    const firstName = name.split(' ')[0];
    items.push({
      id: `${ticker}-news-${i}`,
      headline: `${firstName} ${template.headline}`,
      source: rng.pick(NEWS_SOURCES),
      date: date.toISOString().slice(0, 10),
      ticker,
      sentiment: template.sentiment,
      confidence: rng.int(65, 95),
      impact: template.impact,
      summary: template.summary,
    });
  }
  return items.sort((a, b) => b.date.localeCompare(a.date));
}

function computeAIScore(
  trendBias: number,
  technicals: ReturnType<typeof computeTechnicals>,
  fundamentals: CompanySeed,
  news: NewsItem[],
): AIScore {
  // Technical momentum: based on RSI, MACD, price vs SMA
  const rsiScore = technicals.rsi > 70 ? 65 : technicals.rsi < 30 ? 72 : 50 + (technicals.rsi - 50) * 0.8;
  const macdScore = 50 + technicals.macdHistogram * 20;
  const priceVsSma = fundamentals.basePrice > technicals.sma20 ? 65 : 45;
  const technicalMomentum = Math.round(Math.max(0, Math.min(100, (rsiScore + macdScore + priceVsSma) / 3 + trendBias * 15)));

  // Fundamental health
  const peScore = fundamentals.peRatio < 15 ? 75 : fundamentals.peRatio < 25 ? 60 : 40;
  const growthScore = Math.max(20, Math.min(95, 50 + fundamentals.revenueGrowth * 1.5 + fundamentals.profitGrowth));
  const divScore = fundamentals.dividendYield > 3 ? 75 : fundamentals.dividendYield > 1 ? 60 : 45;
  const debtScore = fundamentals.debtToEquity < 0.4 ? 80 : fundamentals.debtToEquity < 0.7 ? 60 : 40;
  const fundamentalHealth = Math.round((peScore + growthScore + divScore + debtScore) / 4);

  // Market trend
  const marketTrend = Math.round(Math.max(20, Math.min(95, 55 + trendBias * 40)));

  // News sentiment
  const positiveCount = news.filter((n) => n.sentiment === 'POSITIVE').length;
  const negativeCount = news.filter((n) => n.sentiment === 'NEGATIVE').length;
  const newsSentiment = Math.round(Math.max(20, Math.min(95, 50 + (positiveCount - negativeCount) * 15 + trendBias * 10)));

  // Volume (use a proxy from volatility)
  const volumeScore = Math.round(Math.max(30, Math.min(90, 60 + (0.025 - fundamentals.volatility) * 500)));

  // Risk
  const riskScore = Math.round(Math.max(20, Math.min(90, 70 - fundamentals.volatility * 500 - fundamentals.debtToEquity * 20)));

  const components = [
    { label: 'Technical Momentum', score: technicalMomentum, weight: 25 },
    { label: 'Fundamental Health', score: fundamentalHealth, weight: 25 },
    { label: 'Market Trend', score: marketTrend, weight: 15 },
    { label: 'News Sentiment', score: newsSentiment, weight: 15 },
    { label: 'Trading Volume', score: volumeScore, weight: 10 },
    { label: 'Risk / Volatility', score: riskScore, weight: 10 },
  ];

  const total = Math.round(components.reduce((acc, c) => acc + c.score * c.weight, 0) / 100);

  const signal = total >= 65 ? 'BUY' : total <= 45 ? 'AVOID' : 'HOLD';
  const confidence = Math.min(95, Math.max(50, total + 5));

  // Generate reasons
  const reasons: string[] = [];
  if (technicalMomentum > 65) reasons.push(`Positive technical momentum with RSI at ${technicals.rsi.toFixed(0)}`);
  if (technicals.macdHistogram > 0) reasons.push('MACD histogram positive, indicating bullish momentum');
  if (fundamentalHealth > 65) reasons.push(`Strong fundamentals with P/E of ${fundamentals.peRatio.toFixed(1)} and ${fundamentals.revenueGrowth.toFixed(1)}% revenue growth`);
  if (newsSentiment > 60) reasons.push(`${positiveCount} recent positive news items vs ${negativeCount} negative`);
  if (fundamentals.dividendYield > 3) reasons.push(`Attractive dividend yield of ${fundamentals.dividendYield.toFixed(1)}%`);
  if (fundamentals.profitGrowth > 15) reasons.push(`Profit growth of ${fundamentals.profitGrowth.toFixed(1)}% signals improving profitability`);
  if (marketTrend > 60) reasons.push('Stock is in an uptrend relative to recent moving averages');
  if (reasons.length === 0) reasons.push('Mixed signals across technical and fundamental indicators');

  const risks: string[] = [];
  if (technicals.rsi > 70) risks.push('RSI in overbought territory, pullback possible');
  if (technicals.rsi < 30) risks.push('RSI in oversold territory, further decline possible');
  if (fundamentals.volatility > 0.025) risks.push('High price volatility increases uncertainty');
  if (fundamentals.debtToEquity > 0.6) risks.push(`Elevated debt-to-equity ratio of ${fundamentals.debtToEquity.toFixed(2)}`);
  if (negativeCount > positiveCount) risks.push('Recent news sentiment skews negative');
  if (fundamentals.profitGrowth < 0) risks.push('Declining profitability trend');
  if (risks.length === 0) risks.push('Moderate market volatility may affect short-term performance');

  return { total, components, signal, confidence, reasons: reasons.slice(0, 5), risks: risks.slice(0, 3) };
}

function computeForecast(basePrice: number, trendBias: number, vol: number, aiScoreTotal: number): PriceForecast {
  const drift = trendBias * 0.02;
  const vol7 = vol * basePrice * Math.sqrt(7 / 260);
  const vol30 = vol * basePrice * Math.sqrt(30 / 260);

  const base7 = basePrice * (1 + drift * 7);
  const base30 = basePrice * (1 + drift * 30);

  const probPositive = Math.max(15, Math.min(90, 50 + trendBias * 35 + (aiScoreTotal - 50) * 0.3));
  const confidence: Confidence = aiScoreTotal > 70 ? 'HIGH' : aiScoreTotal > 50 ? 'MEDIUM' : 'LOW';
  const expectedVolatility = vol > 0.025 ? 'HIGH' : vol > 0.018 ? 'MEDIUM' : 'LOW';

  return {
    sevenDay: {
      bear: [Math.round((base7 - vol7 * 1.5) * 100) / 100, Math.round((base7 - vol7 * 0.5) * 100) / 100],
      base: [Math.round((base7 - vol7 * 0.5) * 100) / 100, Math.round((base7 + vol7 * 0.5) * 100) / 100],
      bull: [Math.round((base7 + vol7 * 0.5) * 100) / 100, Math.round((base7 + vol7 * 1.5) * 100) / 100],
    },
    thirtyDay: {
      bear: [Math.round((base30 - vol30 * 1.5) * 100) / 100, Math.round((base30 - vol30 * 0.5) * 100) / 100],
      base: [Math.round((base30 - vol30 * 0.5) * 100) / 100, Math.round((base30 + vol30 * 0.5) * 100) / 100],
      bull: [Math.round((base30 + vol30 * 0.5) * 100) / 100, Math.round((base30 + vol30 * 1.5) * 100) / 100],
    },
    probPositiveReturn: Math.round(probPositive),
    confidence,
    expectedVolatility,
  };
}

export function generateStocks(): Stock[] {
  return COMPANIES.map((seed, idx) => {
    const rng = new RNG((idx + 1) * 1000 + 42);
    const history = generateHistory(seed, rng);
    const lastPrice = history[history.length - 1].price;
    const prevPrice = history[history.length - 2].price;
    const dailyChange = Math.round((lastPrice - prevPrice) * 100) / 100;
    const dailyChangePct = Math.round((dailyChange / prevPrice) * 10000) / 100;

    const technicals = computeTechnicals(history);
    const news = generateNews(seed.ticker, seed.name, rng);
    const aiScore = computeAIScore(seed.trendBias, technicals, seed, news);
    const forecast = computeForecast(lastPrice, seed.trendBias, seed.volatility, aiScore.total);

    return {
      ticker: seed.ticker,
      name: seed.name,
      sector: seed.sector,
      currentPrice: lastPrice,
      dailyChange,
      dailyChangePct,
      volume: history[history.length - 1].volume,
      marketCap: seed.marketCap,
      history,
      fundamentals: {
        eps: seed.eps,
        peRatio: seed.peRatio,
        revenueGrowth: seed.revenueGrowth,
        profitGrowth: seed.profitGrowth,
        dividendYield: seed.dividendYield,
        debtToEquity: seed.debtToEquity,
        marketCap: seed.marketCap,
        bookValue: seed.bookValue,
      },
      technicals,
      aiScore,
      forecast,
      news,
    };
  });
}

