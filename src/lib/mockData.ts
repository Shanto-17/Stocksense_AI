function generateHistory(seed: CompanySeed, rng: RNG): PricePoint[] {
  const points: PricePoint[] = [];
  const days = 260; // ~1 year of trading days
  let price = seed.basePrice * rng.range(0.75, 0.9);
  const startDate = new Date();
  startDate.setDate(startDate.getDate() - days);

  for (let i = 0; i < days; i++) {
    const date = new Date(startDate);
    date.setDate(date.getDate() + i);
    // Skip weekends
    if (date.getDay() === 0 || date.getDay() === 6) continue;

    const trendComponent = seed.trendBias * 0.003;
    const noise = (rng.next() - 0.5) * 2 * seed.volatility;
    const change = trendComponent + noise;
    price = price * (1 + change);
    price = Math.max(price, 1);

    const baseVolume = seed.marketCap * 1000;
    const volume = Math.floor(baseVolume * rng.range(0.3, 1.8));

    points.push({
      date: date.toISOString().slice(0, 10),
      price: Math.round(price * 100) / 100,
      volume,
    });
  }
  return points;
}

